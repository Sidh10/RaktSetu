"""Build build_deck_r2.js from the read-only v3 builder: same code for slides 1, 2, 7, 8; slides 3-6 from slides_3_to_6.js."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "RaktSetu_simulator_and_prototype" / "deck_v3" / "build_deck_v3.js"
s = SRC.read_text(encoding="utf-8")
new36 = (HERE / "slides_3_to_6.js").read_text(encoding="utf-8")
a = s.index("// ---------------- Slide 3:")
b = s.index("// ---------------- Slide 7:")
s = s[:a] + new36 + s[b:]
pairs = [
    ("// RaktSetu — Code Apex 3.0 deck, v3 (blood groups, sensitivity, ablation, calibration).",
     "// RaktSetu — Code Apex 3.0 deck, Round 2 version. GENERATED by deck_r2/splice.py from\n"
     "// RaktSetu_simulator_and_prototype/deck_v3/build_deck_v3.js (read-only): slides 1, 2, 7, 8 unchanged;\n"
     "// slides 3-6 replaced (deck_r2/slides_3_to_6.js) to show the built prototype. Do not edit by hand."),
    ('const NUM = require("./deck_numbers.json");',
     'const SIM = path.join(__dirname, "..", "..", "RaktSetu_simulator_and_prototype");\n'
     'const NUM = require(path.join(SIM, "deck_v3", "deck_numbers.json"));'),
    ('const ROOT = path.join(__dirname, "..");', "const ROOT = SIM;"),
    ('pres.title = "RaktSetu — Team Trex — Code Apex 3.0 (v3)";', 'pres.title = "RaktSetu — Team Trex — Code Apex 3.0 (Round 2)";'),
    ('const out = process.argv[2] || path.join(ROOT, "out_v3", "RaktSetu_TeamTrex_CodeApex3_v3.pptx");',
     'const out = process.argv[2] || path.join(__dirname, "out", "RaktSetu_TeamTrex_CodeApex3_Round2.pptx");'),
]
for old, new in pairs:
    assert s.count(old) == 1, old[:60]
    s = s.replace(old, new)
(HERE / "build_deck_r2.js").write_text(s, encoding="utf-8", newline="\n")
print("wrote build_deck_r2.js")
